"""Generates kernel/import_fallback.cpp: a weak, logging definition for every kernel/XAM
import the recompiled code references (PPC_EXTERN_FUNC(__imp__X) in ppc_recomp_shared.h).
Real implementations elsewhere in the runtime are strong symbols and win at link time, so
any import without one still links and prints "[UNIMPLEMENTED IMPORT] X" on its first call.

Usage: python gen_import_fallback.py [ppc_recomp_shared.h] [output.cpp]
Only reads the header; writes the one output file.
"""
import re
import sys
from pathlib import Path

here = Path(__file__).resolve().parent
header = Path(sys.argv[1]) if len(sys.argv) > 1 else Path("<project folder>/builds/ppc/ppc_recomp_shared.h")
output = Path(sys.argv[2]) if len(sys.argv) > 2 else here.parent / "kernel" / "import_fallback.cpp"

names = sorted(set(re.findall(r"PPC_EXTERN_FUNC\(__imp__(\w+)\)", header.read_text(errors="replace"))))

lines = [
    "// GENERATED by tools/gen_import_fallback.py - do not edit by hand.",
    "// Weak fallback for every import referenced by the recompiled code (see import_log.h).",
    "#include <stdafx.h>",
    "#include \"import_log.h\"",
    "",
    "#define IMPORT_FALLBACK(name) \\",
    "    __attribute__((weak)) PPC_FUNC(__imp__##name) \\",
    "    { \\",
    "        static std::atomic<bool> s_logged; \\",
    "        if (!s_logged.exchange(true)) ImportUnimplemented(#name); \\",
    "        ctx.r3.u64 = 0; \\",
    "    }",
    "",
]
lines += [f"IMPORT_FALLBACK({n})" for n in names]
lines.append("")
output.write_text("\n".join(lines), newline="\n")
print(f"{len(names)} imports -> {output}")
