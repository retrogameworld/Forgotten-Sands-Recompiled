"""Writes src/runtime/gpu/renderstate_hooks.inc from this game's render-state table.

D3D's SetStateDefaults (FS sub_821ACD78) walks a global table of {get, set, default} entries:
render states at 0x82EC56D0 (0x65 entries), sampler states at 0x82EC5B90 (0x14 entries).
Every render-state set function gets an RS_HOOK so video.cpp can track the state (as in Torchlight).
Entries that share one stub with the first entries are skipped like Torchlight did (entries 0-9).

Usage: python -I gen_renderstate_hooks.py <image.bin> <out.inc>
Only reads the image and writes the one output file.
"""
import struct
import sys

BASE = 0x82000000
RS_TABLE, RS_COUNT = 0x82EC56D0, 0x65

NAMES = {10: "ZENABLE", 11: "ZFUNC", 12: "ZWRITEENABLE", 13: "FILLMODE", 14: "CULLMODE", 15: "ALPHABLENDENABLE",
         16: "SEPARATEALPHABLENDENABLE", 17: "BLENDFACTOR", 18: "SRCBLEND", 19: "DESTBLEND", 20: "BLENDOP",
         21: "SRCBLENDALPHA", 22: "DESTBLENDALPHA", 23: "BLENDOPALPHA", 24: "ALPHATESTENABLE", 25: "ALPHAREF",
         26: "ALPHAFUNC", 50: "SCISSORTESTENABLE", 51: "SLOPESCALEDEPTHBIAS", 52: "DEPTHBIAS", 53: "COLORWRITEENABLE"}


def main():
    d = open(sys.argv[1], "rb").read()
    entries = [struct.unpack_from(">III", d, RS_TABLE - BASE + i * 12) for i in range(RS_COUNT)]
    stub = entries[0][1]
    lines = ["// GENERATED by src/analysis/gen_renderstate_hooks.py from the render-state table @0x%08X." % RS_TABLE,
             "// RS_HOOK(state index (= D3DRS value / 4), guest set function). Entries using the shared stub 0x%08X are skipped." % stub]
    seen = set()
    for i, (get, set_, default) in enumerate(entries):
        if set_ == stub or set_ in seen:
            continue
        seen.add(set_)
        lines.append("RS_HOOK(%d, sub_%08X) // %d %s" % (i, set_, i * 4, NAMES.get(i, "")))
    open(sys.argv[2], "w", newline="\n").write("\n".join(lines) + "\n")
    print("%d render-state hooks -> %s (shared stub 0x%08X)" % (len(lines) - 2, sys.argv[2], stub))


if __name__ == "__main__":
    main()
